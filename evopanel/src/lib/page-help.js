// ─── 向后兼容：旧版结构自动映射 ────────────────────────────

function normalizeGuide(raw) {
  if (!raw) return null
  // 已是 v2 结构（有 overview）
  if (raw.overview) return raw
  // 旧版 v1 结构（直接有 what/when/how）
  return {
    title: raw.title || '',
    icon: raw.icon || '📖',
    overview: {
      what: raw.what || '',
      when: raw.when || '',
      how: raw.how || '',
    },
  }
}

// ─── 路由匹配 ───────────────────────────────────────────────

/**
 * 根据当前路由获取指南内容
 * @param {string} route - 当前路由路径
 * @returns {object | null}
 */
export function getHelpForRoute(route) {
  if (!route) return null

  // 精确匹配
  if (GUIDE[route]) return normalizeGuide(GUIDE[route])

  // 动态路由精确匹配（带 :param 模式）
  const dynamicKeys = Object.keys(GUIDE).filter((k) => k.includes(':'))
  for (const key of dynamicKeys) {
    const pattern = new RegExp('^' + key.replace(/:[^/]+/g, '[^/]+') + '$')
    if (pattern.test(route)) return normalizeGuide(GUIDE[key])
  }

  // 前缀匹配（如 /apps/xxx → /apps）
  const prefixMatch = Object.keys(GUIDE).find((key) => {
    if (key === route || key.includes(':')) return false
    return route.startsWith(key + '/')
  })
  if (prefixMatch) return normalizeGuide(GUIDE[prefixMatch])

  // 特殊兜底映射（动态 :id 未命中时）
  if (route.startsWith('/task/')) return normalizeGuide(GUIDE['/task/:id'])
  // 工作流编辑器优先于列表页指南
  if (route.startsWith('/apps/') && route !== '/apps') return normalizeGuide(GUIDE['/apps/:id'] || GUIDE['/apps'])
  if (route.startsWith('/agents/team/')) return normalizeGuide(GUIDE['/agents/team/:code'] || GUIDE['/agents'])
  if (route.startsWith('/agents/')) return normalizeGuide(GUIDE['/agents'])
  if (route === '/proactive/board') return normalizeGuide(GUIDE['/proactive/board'])
  if (route.startsWith('/proactive/') && route !== '/proactive') {
    return normalizeGuide(GUIDE['/proactive/:code'] || GUIDE['/proactive'])
  }
  if (route.startsWith('/workflow/')) return normalizeGuide(GUIDE['/workflow/:id'])
  if (route.startsWith('/runs/')) return normalizeGuide(GUIDE['/runs/:runId'])
  if (route.startsWith('/project/')) return normalizeGuide(GUIDE['/project/:id'])
  if (route === '/knowledge' || route.startsWith('/knowledge/')) return normalizeGuide(GUIDE['/knowledge'])

  return null
}

// ─── 工具函数 ───────────────────────────────────────────────

function _esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

// 简单的换行转 <br>，支持 **粗体** 和 `code`
function _renderText(s) {
  let html = _esc(s)
  html = html.replace(/`([^`]+)`/g, '<code>$1</code>')
  html = html.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
  html = html.replace(/\n/g, '<br>')
  return html
}

