// Tab 切换
function _switchTab(guide, tab) {
  _currentTab = tab
  if (!_currentPanel) return

  // 更新 Tab 按钮状态
  _currentPanel.querySelectorAll('.guide-tab').forEach((btn) => {
    const isActive = btn.dataset.tab === tab
    btn.classList.toggle('is-active', isActive)
    btn.setAttribute('aria-selected', String(isActive))
  })

  // 更新内容
  const body = _currentPanel.querySelector('#guide-panel-body')
  if (body) {
    body.innerHTML = _renderTabContent(guide, tab)
    // 重新绑定交互
    if (tab === 'faq') _bindFaqAccordion(_currentPanel)
    if (tab === 'docs') _bindDocLinks(_currentPanel, guide)
  }
}

// FAQ 折叠交互
function _bindFaqAccordion(root) {
  root.querySelectorAll('.guide-faq-item').forEach((item) => {
    const btn = item.querySelector('.guide-faq-q')
    btn?.addEventListener('click', () => {
      const isOpen = item.classList.contains('is-open')
      // 手风琴：只开一个
      root.querySelectorAll('.guide-faq-item').forEach((i) => {
        i.classList.remove('is-open')
        i.querySelector('.guide-faq-q')?.setAttribute('aria-expanded', 'false')
      })
      if (!isOpen) {
        item.classList.add('is-open')
        btn.setAttribute('aria-expanded', 'true')
      }
    })
  })
}

// 文档链接交互
function _bindDocLinks(root, guide) {
  if (!guide.docs || !guide.docs.length) return

  // 单个文档项点击
  root.querySelectorAll('.guide-doc-item').forEach((el) => {
    const idx = parseInt(el.dataset.docIndex, 10)
    const doc = guide.docs[idx]
    if (!doc) return

    // 有 search / route 的，用 JS 处理（search 在弹窗内打开正文）
    if (doc.search || doc.route) {
      el.addEventListener('click', (e) => {
        e.preventDefault()
        void _handleDocAction(doc)
      })
    }
    // 禁用项不跳转
    if (el.classList.contains('is-disabled')) {
      el.addEventListener('click', (e) => {
        e.preventDefault()
      })
    }
  })

  // 浏览用户指南全部文档（弹窗内，不跳知识库页）
  const vaultBtn = root.querySelector('#guide-open-vault')
  vaultBtn?.addEventListener('click', () => {
    void _browseUserGuideVault()
  })
}

