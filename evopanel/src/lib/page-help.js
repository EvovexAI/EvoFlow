/**
 * 弹出当前页「使用指南」面板
 * @param {string} [route]
 * @param {string} [initialTab] - 初始 Tab
 */
export function showPageHelpPanel(route, initialTab) {
  const current = String(route || getCurrentRoute() || '/chat').split('?')[0]
  const normalized = current.startsWith('/') ? current : `/${current}`
  const guide = getHelpForRoute(normalized) || getHelpForRoute('/chat')

  if (!guide) {
    toast('当前页面暂无使用说明', 'info')
    return
  }

  // 关掉已有的
  if (_currentPanel) {
    _currentPanel.remove()
    _currentPanel = null
  }

  _currentTab = initialTab || 'overview'
  _currentGuide = guide

  const panel = document.createElement('div')
  panel.id = 'help-panel'
  panel.className = 'help-panel guide-panel-v2'
  panel.setAttribute('role', 'dialog')
  panel.setAttribute('aria-label', guide.title + '使用指南')

  const hasSteps = guide.steps && guide.steps.length > 0
  const hasFaq = guide.faq && guide.faq.length > 0
  const hasDocs = guide.docs && guide.docs.length > 0
  const hasTabs = hasSteps || hasFaq || hasDocs

  const tabsHtml = hasTabs ? `
    <div class="guide-tabs" role="tablist">
      <button class="guide-tab ${_currentTab === 'overview' ? 'is-active' : ''}" data-tab="overview" role="tab" aria-selected="${_currentTab === 'overview'}">
        <span class="guide-tab-icon">📖</span>
        <span>概览</span>
      </button>
      ${hasSteps ? `
        <button class="guide-tab ${_currentTab === 'steps' ? 'is-active' : ''}" data-tab="steps" role="tab" aria-selected="${_currentTab === 'steps'}">
          <span class="guide-tab-icon">👣</span>
          <span>操作</span>
        </button>
      ` : ''}
      ${hasFaq ? `
        <button class="guide-tab ${_currentTab === 'faq' ? 'is-active' : ''}" data-tab="faq" role="tab" aria-selected="${_currentTab === 'faq'}">
          <span class="guide-tab-icon">❓</span>
          <span>FAQ</span>
        </button>
      ` : ''}
      ${hasDocs ? `
        <button class="guide-tab ${_currentTab === 'docs' ? 'is-active' : ''}" data-tab="docs" role="tab" aria-selected="${_currentTab === 'docs'}">
          <span class="guide-tab-icon">📄</span>
          <span>更多文档</span>
        </button>
      ` : ''}
    </div>
  ` : ''

  panel.innerHTML = `
    <div class="help-panel-header guide-panel-header">
      <div class="guide-panel-title-wrap">
        <span class="guide-panel-icon">${_esc(guide.icon || '📖')}</span>
        <span class="help-panel-title">${_esc(guide.title)} · 使用指南</span>
      </div>
      <button type="button" class="help-panel-close" id="help-panel-close" aria-label="关闭">
        <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2">
          <line x1="18" y1="6" x2="6" y2="18"/>
          <line x1="6" y1="6" x2="18" y2="18"/>
        </svg>
      </button>
    </div>
    ${tabsHtml}
    <div class="help-panel-body guide-panel-body" id="guide-panel-body">
      ${_renderTabContent(guide, _currentTab)}
    </div>
  `

  document.body.appendChild(panel)
  _currentPanel = panel

  // 关闭事件
  panel.querySelector('#help-panel-close')?.addEventListener('click', () => _closePanel())
  panel.addEventListener('click', (e) => {
    // 点击遮罩（::before 区域，即面板本身外的背景）关闭
    if (e.target === panel) _closePanel()
  })

  // Tab 切换
  panel.querySelectorAll('.guide-tab').forEach((btn) => {
    btn.addEventListener('click', () => {
      const tab = btn.dataset.tab
      if (!tab || tab === _currentTab) return
      _switchTab(guide, tab)
    })
  })

  // FAQ 折叠
  _bindFaqAccordion(panel)

  // 文档链接
  _bindDocLinks(panel, guide)

  // Esc 关闭
  const onKey = (e) => {
    if (e.key === 'Escape') {
      _closePanel()
      document.removeEventListener('keydown', onKey)
    }
  }
  document.addEventListener('keydown', onKey)
  panel._onKeyHandler = onKey
}

